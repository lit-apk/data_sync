val generatedFormatDir = layout.buildDirectory.dir("generated/documentFormats/kotlin").get().asFile

val generateDocumentFormats by tasks.registering {
    notCompatibleWithConfigurationCache("The source scanner is implemented in the build script")
    inputs.files(fileTree("src/main/java") { include("**/*.kt") })
    outputs.dir(generatedFormatDir)
    doLast {
        val outputDir = generatedFormatDir
        val packageDir = File(outputDir, "top/lighilit/watch_data_sync")
        packageDir.mkdirs()
        // @DocumentBackend(MimeType.EPUB, ...) class/object Name : DocumentFormat
        val backendPattern = Regex("@DocumentBackend\\(([^)]*)\\)\\s+(?:internal\\s+)?(class|object)\\s+(\\w+)\\s*:")
        val backends = fileTree("src/main/java")
            .matching { include("**/*.kt") }
            .files
            .flatMap { file ->
                backendPattern.findAll(file.readText()).map { match ->
                    val mimes = match.groupValues[1].split(',').map { it.trim().removePrefix("MimeType.") }
                        .filter { it.isNotEmpty() }
                    require(mimes.isNotEmpty()) { "@DocumentBackend on ${match.groupValues[3]} lists no MimeType" }
                    Triple(match.groupValues[2], match.groupValues[3], mimes)
                }.toList()
            }
            .distinctBy { it.second }
            .sortedBy { it.second }
        require(backends.isNotEmpty()) { "No @DocumentBackend implementations found" }
        File(packageDir, "GeneratedDocumentFormats.java").writeText(
            "package top.lighilit.watch_data_sync;\n\n" +
                "final class GeneratedDocumentFormats {\n" +
                "    static java.util.List<BackendRegistration> all() {\n" +
                "        return java.util.Arrays.asList(\n" +
                backends.joinToString(",\n") { (kind, name, mimes) ->
                    val instance = if (kind == "object") "$name.INSTANCE" else "new $name()"
                    val types = mimes.joinToString(", ") { "MimeType.$it" }
                    "            new BackendRegistration($instance, java.util.Arrays.asList($types))"
                } +
                "\n        );\n    }\n}\n"
        )
    }
}

android.sourceSets["main"].java.directories.add(generatedFormatDir.absolutePath)
tasks.named("preBuild") { dependsOn(generateDocumentFormats) }

/**
 * Writes a manifest fragment with the "Open with" (VIEW) and "Share" (SEND) intent filters
 * for MainActivity, one <data android:mimeType> per MimeType value and alias. The manifest
 * merger adds the filters to the hand-written MainActivity, so new formats need no manifest edit.
 */
abstract class GenerateOpenWithManifest : DefaultTask() {
    @get:InputFile
    abstract val mimeTypeSource: RegularFileProperty

    @get:OutputFile
    abstract val manifest: RegularFileProperty

    @TaskAction
    fun generate() {
        // One entry per line: NAME("value", listOf(...), ..., aliases = listOf("a", "b")),
        val entry = Regex("""^\s+[A-Z][A-Z0-9_]*\(\s*"([^"]+)"(.*)$""", RegexOption.MULTILINE)
        val aliases = Regex("""aliases\s*=\s*listOf\(([^)]*)\)""")
        val quoted = Regex("\"([^\"]+)\"")
        val types = entry.findAll(mimeTypeSource.get().asFile.readText()).flatMap { match ->
            val extra = aliases.find(match.groupValues[2])?.groupValues?.get(1).orEmpty()
            sequenceOf(match.groupValues[1]) + quoted.findAll(extra).map { it.groupValues[1] }
        }.distinct().toList()
        require(types.isNotEmpty()) { "No MimeType entries found in ${mimeTypeSource.get().asFile}" }
        val data = types.joinToString("\n") { "                <data android:mimeType=\"$it\" />" }
        manifest.get().asFile.writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- GENERATED by generateOpenWithManifest from MimeType.kt; do not edit. -->
            |<manifest xmlns:android="http://schemas.android.com/apk/res/android">
            |    <application>
            |        <activity android:name="top.lighilit.watch_data_sync.MainActivity" android:exported="true">
            |            <intent-filter>
            |                <action android:name="android.intent.action.VIEW" />
            |                <category android:name="android.intent.category.DEFAULT" />
            |                <category android:name="android.intent.category.BROWSABLE" />
            |                <data android:scheme="content" />
            |                <data android:scheme="file" />
            |$data
            |            </intent-filter>
            |            <intent-filter>
            |                <action android:name="android.intent.action.SEND" />
            |                <category android:name="android.intent.category.DEFAULT" />
            |$data
            |            </intent-filter>
            |        </activity>
            |    </application>
            |</manifest>
            |""".trimMargin()
        )
    }
}

val generateOpenWithManifest by tasks.registering(GenerateOpenWithManifest::class) {
    mimeTypeSource.set(layout.projectDirectory.file("src/main/java/top/lighilit/watch_data_sync/MimeType.kt"))
    manifest.set(layout.buildDirectory.file("generated/openWithManifest/AndroidManifest.xml"))
}

/** Runs a git command, returning its trimmed stdout or "" when git is unavailable or fails. */
fun git(vararg cmd: String): String =
    runCatching {
        val process = ProcessBuilder(*cmd).redirectErrorStream(true).start()
        val out = process.inputStream.bufferedReader().readText()
        if (process.waitFor() == 0) out.trim() else ""
    }.getOrElse { "" }

/**
 * Captures git commit, branch, and dirty state at build time and writes them into a generated
 * Java source file. Runs in a task (not configuration time) so the configuration cache stays
 * happy. The generated file is added as a source directory so the app can read the values.
 */
val gitInfoSourceDir = layout.buildDirectory.dir("generated/gitInfo/java").get().asFile
val gitBuildInfo by tasks.registering {
    notCompatibleWithConfigurationCache("The git info task is implemented in the build script")
    outputs.dir(gitInfoSourceDir)
    doLast {
        val packageDir = File(gitInfoSourceDir, "top/lighilit/watch_data_sync")
        packageDir.mkdirs()
        val commit = git("git", "rev-parse", "HEAD")
        val branch = git("git", "rev-parse", "--abbrev-ref", "HEAD")
        val dirty = if (git("git", "status", "--porcelain").isNotEmpty()) "1" else "0"
        File(packageDir, "GitInfo.java").writeText(
            "package top.lighilit.watch_data_sync;\n\n" +
                "final class GitInfo {\n" +
                "    static final String COMMIT = \"$commit\";\n" +
                "    static final String BRANCH = \"$branch\";\n" +
                "    static final String DIRTY = \"$dirty\";\n" +
                "}\n"
        )
    }
}

android.sourceSets["main"].java.directories.add(gitInfoSourceDir.absolutePath)
tasks.named("preBuild") { dependsOn(gitBuildInfo) }

